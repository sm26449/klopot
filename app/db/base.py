"""SQLAlchemy declarative base + naming convention.

The naming convention makes constraint names deterministic across
migration runs (avoids autogenerated names like
``ix_e0a3c2_template_id`` that change between environments).

Pattern reference:
https://alembic.sqlalchemy.org/en/latest/naming.html
"""
from __future__ import annotations

from sqlalchemy import MetaData
from sqlalchemy.orm import DeclarativeBase

NAMING_CONVENTION = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    """Single declarative base for all ORM models."""

    metadata = MetaData(naming_convention=NAMING_CONVENTION)
